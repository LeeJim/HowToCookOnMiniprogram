// ── 分类函数 ──
function classify(name) {
  // 先检查别名
  if (aliases[name]) return aliases[name];

  const lower = name.toLowerCase();

  for (const [cat, keywords] of Object.entries(categories)) {
    for (const kw of keywords) {
      if (name.includes(kw) || kw.includes(name)) {
        return cat;
      }
    }
  }

  // 兜底规则
  if (/[酱料油盐糖醋酒酱油粉精汁素酱膏蜜乳浆]$/.test(name) || /^[酱料油盐糖醋酒]/.test(name)) {
    return '调料';
  }
  if (/[锅碗瓢盆壶盘碟杯筷勺铲刀秤器皿模具机箱炉罩架屉网纸膜袋套]$/.test(name)) {
    return '工具';
  }
  if (/[肉鱼虾蟹贝蚝蛋奶鸡鸭鹅猪牛羊兔鸽腿排翅尾]$/.test(name)) {
    return '荤';
  }
  if (/[菜豆瓜果笋菇菌耳茄椒薯芋藕萝卜仁米面麦粉稻饭饼包饺皮食]$/.test(name)) {
    return '素';
  }
  if (/[桂花叶]$/.test(name)) {
    return '配菜';
  }

  return '其他';
}

// ── 执行分类 ──
const result = { 荤: [], 素: [], 配菜: [], 调料: [], 工具: [], 其他: [] };
const unknown = [];

Object.entries(ingredientCount).forEach(([name, count]) => {
  const cat = classify(name);
  if (result[cat]) {
    result[cat].push({ name, count });
  } else {
    unknown.push({ name, count });
  }
});

// 每个类别按使用次数排序
Object.keys(result).forEach(cat => {
  result[cat].sort((a, b) => b.count - a.count);
});

// ── 输出统计 ──
console.log('\n=== 分类统计 ===');
Object.entries(result).forEach(([cat, items]) => {
  console.log(`${cat}: ${items.length} 项`);
});
if (unknown.length) {
  console.log(`未分类: ${unknown.length} 项`);
}

// ── 写入文件 ──
const outPath = path.join(__dirname, '..', 'classified-ingredients.json');
fs.writeFileSync(outPath, JSON.stringify(result, null, 2), 'utf8');
console.log(`\n已写入: ${outPath}`);

